CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    password_hash TEXT,
    password_salt BYTEA,
    email_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_case_insensitive
    ON users (lower(email));

CREATE TABLE IF NOT EXISTS workspaces (
    id UUID PRIMARY KEY,
    owner_user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS oauth_identities (
    provider TEXT NOT NULL,
    subject TEXT NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (provider, subject)
);

CREATE TABLE IF NOT EXISTS auth_sessions (
    token_digest BYTEA PRIMARY KEY,
    csrf_digest BYTEA NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS auth_sessions_user_expiry
    ON auth_sessions (user_id, expires_at);

CREATE TABLE IF NOT EXISTS auth_tokens (
    token_digest BYTEA PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose TEXT NOT NULL CHECK (purpose IN ('verify_email', 'reset_password')),
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS auth_tokens_user_purpose
    ON auth_tokens (user_id, purpose, expires_at);

CREATE TABLE IF NOT EXISTS leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id UUID NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    phone TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    source TEXT NOT NULL DEFAULT 'Manual',
    timeline TEXT NOT NULL DEFAULT '',
    budget TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    consent_sms BOOLEAN NOT NULL DEFAULT FALSE,
    consent_call BOOLEAN NOT NULL DEFAULT FALSE,
    stage TEXT NOT NULL DEFAULT 'new'
        CHECK (stage IN ('new', 'qualified', 'nurture', 'appointment', 'under_contract', 'closed', 'disqualified')),
    score INTEGER CHECK (score BETWEEN 0 AND 100),
    qualification JSONB NOT NULL DEFAULT '{}'::jsonb,
    crm_ref TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, workspace_id)
);

CREATE INDEX IF NOT EXISTS leads_workspace_created
    ON leads (workspace_id, created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS leads_workspace_stage
    ON leads (workspace_id, stage, created_at DESC);

CREATE TABLE IF NOT EXISTS appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id UUID NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    lead_id BIGINT NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    kind TEXT NOT NULL DEFAULT 'Consultation',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (lead_id, workspace_id)
        REFERENCES leads(id, workspace_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS appointments_workspace_start
    ON appointments (workspace_id, starts_at);

CREATE TABLE IF NOT EXISTS activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id UUID NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    lead_id BIGINT,
    kind TEXT NOT NULL,
    detail TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (lead_id, workspace_id)
        REFERENCES leads(id, workspace_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS activities_workspace_created
    ON activities (workspace_id, id DESC);

CREATE TABLE IF NOT EXISTS workspace_settings (
    workspace_id UUID NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    key TEXT NOT NULL,
    value TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, key)
);

CREATE TABLE IF NOT EXISTS integration_secrets (
    workspace_id UUID NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    key TEXT NOT NULL,
    ciphertext BYTEA NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, key)
);

CREATE TABLE IF NOT EXISTS integration_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id UUID NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    payload JSONB NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'processing', 'succeeded', 'failed')),
    attempts INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS integration_deliveries_pending
    ON integration_deliveries (available_at, id)
    WHERE status IN ('pending', 'failed');

CREATE TABLE IF NOT EXISTS data_migrations (
    migration_key TEXT PRIMARY KEY,
    completed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS schema_migrations (
    version TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
